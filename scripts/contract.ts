/**
 * Publishes the MCP contract: what a model sees when it connects.
 *
 *   npm run contract         write docs/contract.json and docs/CONTRACT.md
 *   npm run contract:check   exit 1 if the committed contract differs from the server
 *
 * MCP servers describe themselves at runtime (tools/list, resources/templates/list,
 * prompts/list), so this asks a real server instead of keeping a hand-written spec.
 * Committing the result makes every change to a tool name, description or schema
 * show up in review. Descriptions are instructions to a model, so they are
 * reviewed like code (and a silent change after users approved the tools is the
 * "rug pull" attack the check guards against).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/client";
import { InMemoryTransport } from "@modelcontextprotocol/server";
import { loadDepositLaws } from "../src/data/load";
import { createDepositLawCore } from "../src/core/depositLaws";
import { createServer, SERVER_NAME, SERVER_TITLE, SERVER_VERSION } from "../src/mcp/server";

const docs = (name: string) => fileURLToPath(new URL(`../docs/${name}`, import.meta.url));

const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
const server = createServer(createDepositLawCore(loadDepositLaws()));
await server.connect(serverSide);
const client = new Client({ name: "contract", version: "0.0.0" });
await client.connect(clientSide);

const { tools } = await client.listTools();
const { resourceTemplates } = await client.listResourceTemplates();
const { prompts } = await client.listPrompts();
const instructions = client.getInstructions?.() ?? "";
await client.close();

const contract = {
  server: { name: SERVER_NAME, title: SERVER_TITLE, version: SERVER_VERSION, instructions },
  tools: tools.map(({ name, title, description, inputSchema, outputSchema, annotations }) => ({
    name, title, description, inputSchema, outputSchema, annotations,
  })),
  resourceTemplates: resourceTemplates.map(({ name, title, uriTemplate, description, mimeType }) => ({
    name, title, uriTemplate, description, mimeType,
  })),
  prompts: prompts.map(({ name, title, description, arguments: args }) => ({ name, title, description, arguments: args })),
};

type JsonSchema = { properties?: Record<string, JsonSchema & { description?: string }>; required?: string[]; type?: string; pattern?: string; minItems?: number; maxItems?: number; items?: JsonSchema };

function describeType(schema: JsonSchema): string {
  if (schema.type === "array") {
    const range = schema.minItems !== undefined ? ` (${schema.minItems}–${schema.maxItems ?? "∞"} items)` : "";
    return `array of ${schema.items ? describeType(schema.items) : "any"}${range}`;
  }
  return schema.pattern ? `${schema.type} matching \`${schema.pattern}\`` : (schema.type ?? "any");
}

function inputTable(schema: JsonSchema): string[] {
  const props = Object.entries(schema.properties ?? {});
  if (!props.length) return ["No input."];
  return [
    "| Input | Type | Required | Description |",
    "|---|---|---|---|",
    ...props.map(([key, value]) =>
      `| \`${key}\` | ${describeType(value)} | ${schema.required?.includes(key) ? "yes" : "no"} | ${value.description ?? ""} |`),
  ];
}

const markdown = [
  `# MCP contract: ${SERVER_TITLE}`,
  "",
  "> Generated by `npm run contract` from the running server. Don't edit by hand; CI fails if it is out of date.",
  "> Machine-readable version: [contract.json](contract.json).",
  "",
  `Server \`${SERVER_NAME}\` ${SERVER_VERSION}. Transport: stdio.`,
  "",
  "**Instructions the server gives the model:**",
  "",
  `> ${instructions}`,
  "",
  "## Tools",
  "",
  ...contract.tools.flatMap((tool) => [
    `### \`${tool.name}\`: ${tool.title ?? ""}`,
    "",
    tool.description ?? "",
    "",
    ...inputTable(tool.inputSchema as JsonSchema),
    "",
    `Output: structured (\`outputSchema\` in contract.json) plus a text summary. Annotations: ${Object.entries(tool.annotations ?? {})
      .filter(([key]) => key.endsWith("Hint"))
      .map(([key, value]) => `${key}=${value}`)
      .join(", ")}.`,
    "",
  ]),
  "## Resources",
  "",
  ...contract.resourceTemplates.flatMap((r) => [`- \`${r.uriTemplate}\` (${r.mimeType}): ${r.description}`]),
  "",
  "## Prompts",
  "",
  ...contract.prompts.flatMap((p) => [
    `### \`${p.name}\`: ${p.title ?? ""}`,
    "",
    p.description ?? "",
    "",
    "| Argument | Required | Description |",
    "|---|---|---|",
    ...(p.arguments ?? []).map((a) => `| \`${a.name}\` | ${a.required ? "yes" : "no"} | ${a.description ?? ""} |`),
    "",
  ]),
].join("\n");

const json = `${JSON.stringify(contract, null, 2)}\n`;

if (process.argv.includes("--check")) {
  const stale = [["contract.json", json], ["CONTRACT.md", markdown]].filter(([name, content]) => {
    try {
      return readFileSync(docs(name!), "utf8") !== content;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`The MCP contract changed: ${stale.map(([name]) => `docs/${name}`).join(", ")} out of date.`);
    console.error("Review the change (tool descriptions are instructions to models), then run: npm run contract");
    process.exit(1);
  }
  console.log("MCP contract matches docs/contract.json and docs/CONTRACT.md.");
} else {
  writeFileSync(docs("contract.json"), json);
  writeFileSync(docs("CONTRACT.md"), markdown);
  console.log(`Wrote docs/contract.json and docs/CONTRACT.md: ${contract.tools.length} tools, ${contract.resourceTemplates.length} resource template, ${contract.prompts.length} prompt.`);
}
